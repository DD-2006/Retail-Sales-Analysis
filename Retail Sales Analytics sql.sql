-- 3. InnerJoin for Order Details
-- Join orders, order_items, and products to display detailed line items.
select o.order_id,p.product_name,oi.quantity,oi.discount,oi.total_price
 from capstone.orderss o
inner join capstone.order_items oi
on o.order_id=oi.order_id
inner join capstone.products p 
on oi.product_id=p.product_id;

-- 4. Total Sales by Store
-- Write a query to group sales (total_price) by each store_id.
select st.store_name,sum(oi.total_price) as TP
from capstone.order_items oi
inner join capstone.orderss o
on o.order_id=oi.order_id
inner join capstone.stores st
on o.order_id=st.store_id
group by st.store_name;

