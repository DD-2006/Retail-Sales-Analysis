-- 6. Customer Purchase Summary
-- For each customer, return total orders placed, total items purchased,and total revenue.
select c.customer_id, c.first_name,c.last_name,
count(o.order_id) as tot_ord_plc,sum(oi.quantity) as tot_item_purch,sum(oi.total_price) as total_revenue 
from customers c
join orderss o
on c.customer_id=o.customer_id
join order_items oi
on o.order_id=oi.order_id
group by c.customer_id
order by total_revenue;

